package com.petclinic.vet.dto;

import java.time.LocalDate;
import java.time.LocalTime;

/**
 * DTO returned from the API for appointment data.
 * Includes vet and specialty names for display without extra lookups.
 */
public class AppointmentResponseDto {

    private Integer id;
    private String petName;
    private String petOwnerName;

    /** Vet ID for reference */
    private Integer vetId;

    /** Full display name of the assigned vet (e.g. "James Carter") */
    private String vetName;

    /** Specialty ID (nullable if not specified) */
    private Integer specialtyId;

    /** Name of the specialty (nullable) */
    private String specialtyName;

    private LocalDate appointmentDate;
    private LocalTime appointmentTime;
    private String reason;
    private String status;

    public AppointmentResponseDto() {
    }

    // --- Getters and Setters ---

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public String getPetName() {
        return petName;
    }

    public void setPetName(String petName) {
        this.petName = petName;
    }

    public String getPetOwnerName() {
        return petOwnerName;
    }

    public void setPetOwnerName(String petOwnerName) {
        this.petOwnerName = petOwnerName;
    }

    public Integer getVetId() {
        return vetId;
    }

    public void setVetId(Integer vetId) {
        this.vetId = vetId;
    }

    public String getVetName() {
        return vetName;
    }

    public void setVetName(String vetName) {
        this.vetName = vetName;
    }

    public Integer getSpecialtyId() {
        return specialtyId;
    }

    public void setSpecialtyId(Integer specialtyId) {
        this.specialtyId = specialtyId;
    }

    public String getSpecialtyName() {
        return specialtyName;
    }

    public void setSpecialtyName(String specialtyName) {
        this.specialtyName = specialtyName;
    }

    public LocalDate getAppointmentDate() {
        return appointmentDate;
    }

    public void setAppointmentDate(LocalDate appointmentDate) {
        this.appointmentDate = appointmentDate;
    }

    public LocalTime getAppointmentTime() {
        return appointmentTime;
    }

    public void setAppointmentTime(LocalTime appointmentTime) {
        this.appointmentTime = appointmentTime;
    }

    public String getReason() {
        return reason;
    }

    public void setReason(String reason) {
        this.reason = reason;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }
}
